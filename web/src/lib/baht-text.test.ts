import { expect, test } from 'bun:test'
import { bahtText } from './baht-text'

const cases: [number, string][] = [
  [0, 'ศูนย์บาทถ้วน'],
  [1, 'ศูนย์บาทหนึ่งสตางค์'],
  [100, 'หนึ่งบาทถ้วน'],
  [1100, 'สิบเอ็ดบาทถ้วน'],
  [2100, 'ยี่สิบเอ็ดบาทถ้วน'],
  [2000, 'ยี่สิบบาทถ้วน'],
  [1000, 'สิบบาทถ้วน'],
  [10100, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
  [123450, 'หนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์'],
  [100_000_100, 'หนึ่งล้านเอ็ดบาทถ้วน'],
  [100_000_000, 'หนึ่งล้านบาทถ้วน'],
  [1_000_000_000, 'สิบล้านบาทถ้วน'],
  [2125, 'ยี่สิบเอ็ดบาทยี่สิบห้าสตางค์'],
  [101, 'หนึ่งบาทหนึ่งสตางค์'],
  [121, 'หนึ่งบาทยี่สิบเอ็ดสตางค์'],
  [500_000, 'ห้าพันบาทถ้วน'],
  [1_234_567_89, 'หนึ่งล้านสองแสนสามหมื่นสี่พันห้าร้อยหกสิบเจ็ดบาทแปดสิบเก้าสตางค์'],
  [1_000_000_000_000, 'หนึ่งหมื่นล้านบาทถ้วน'],
  [-123450, 'ลบหนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์'],
]
for (const [s, t] of cases) test(`bahtText(${s})`, () => expect(bahtText(s)).toBe(t))

test('million boundary: 1,000,000 and 1,000,001 baht', () => {
  expect(bahtText(100_000_000)).toBe('หนึ่งล้านบาทถ้วน')
  expect(bahtText(100_000_100)).toBe('หนึ่งล้านเอ็ดบาทถ้วน')
})
test('repeated ล้าน for >1e12 baht', () => {
  expect(bahtText(100_000_000_000_000)).toBe('หนึ่งล้านล้านบาทถ้วน')
})
test('rejects non-integers', () => {
  expect(() => bahtText(1.5)).toThrow()
})
